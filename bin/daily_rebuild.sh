#!/usr/bin/env bash
# =============================================================================
# daily_rebuild.sh — deterministic full REPLACE + FAIL-CLOSED commit for the
# JIVO Data Bank.
#
# Each run rebuilds the entire combined vault from the CURRENT source vaults,
# proves zero data loss, verifies the product/hub/link backbone, and ONLY
# commits if every gate passes. One pass = one commit, so git history is a
# time machine (yesterday's data == yesterday's commit). Accuracy at all costs:
# on ANY loss/regression it aborts WITHOUT committing and alerts.
#
# Cron-ready (idempotent, single-flight lock, absolute paths). NOT installed as
# a cron by this script — see RUNBOOK.md for the suggested schedule.
#
# Override any path via environment variables (defaults shown below).
# =============================================================================
set -euo pipefail

REPO="${JDB_REPO:-/root/jivo-data-bank}"             # the standalone git repo (and Obsidian vault)
COMBINED="${JDB_COMBINED:-/opt/ecom-intel/combined-vault}"  # where the generators build
GEN_DIR="${JDB_GEN_DIR:-/opt/ecom-intel/bin}"        # source-of-truth generator scripts
JIVO_SRC="${JDB_JIVO_SRC:-/root/jivo-intel/vault}"   # JIVO app vault (needs periodic owner re-auth+pull)
ECOM_SRC="${JDB_ECOM_SRC:-/opt/ecom-intel/vault}"    # ecom price vault (refreshed daily by existing crons)
PY="${JDB_PYTHON:-python3}"
# auto = re-apply the cached semantic links if .links/ is present (cheap); the
# EXPENSIVE regeneration of that cache (agent fan-out) is a separate weekly job.
RUN_SEMANTIC="${JDB_SEMANTIC:-auto}"                 # auto | yes | no
LOG="${JDB_LOG:-$REPO/bin/daily_rebuild.log}"

ts() { date -u +%Y-%m-%dT%H:%M:%SZ; }
log() { echo "[$(ts)] $*" | tee -a "$LOG" >&2; }

alert() {
    log "ABORT: $*"
    # best-effort owner alert; never let alerting failure mask the abort
    if [ -x /root/.claude/hooks/notify.sh ]; then
        /root/.claude/hooks/notify.sh "JIVO data-bank rebuild ABORTED: $*" >/dev/null 2>&1 || true
    fi
}

# ---- single-flight lock (cron-safe) -----------------------------------------
LOCK="$REPO/.daily_rebuild.lock"
exec 9>"$LOCK"
if ! flock -n 9; then
    log "another rebuild holds the lock; exiting cleanly"
    exit 0
fi

log "=== daily_rebuild start (REPO=$REPO COMBINED=$COMBINED SEMANTIC=$RUN_SEMANTIC) ==="

# ---- 0. preflight: every prerequisite must exist ----------------------------
for p in "$JIVO_SRC" "$ECOM_SRC" \
         "$GEN_DIR/combined_migrate.py" "$GEN_DIR/combined_backbone.py" \
         "$REPO/bin/verify_databank.py" "$REPO/.git"; do
    [ -e "$p" ] || { alert "missing prerequisite: $p"; exit 2; }
done

# Keep the repo's generator snapshots in lock-step with what actually built it.
cp -f "$GEN_DIR"/combined_migrate.py "$GEN_DIR"/combined_backbone.py \
      "$GEN_DIR"/combined_inject_links.py "$REPO/bin/" 2>/dev/null || true

# ---- 1. deterministic clean mirror ------------------------------------------
# Wipe the copied source subtrees so DELETIONS in the source propagate (true
# REPLACE, not a merge). products/ hubs/ Home.md .manifest.json are fully
# regenerated by the backbone. The .links/ semantic cache is preserved for the
# cheap daily re-injection below.
log "step 1: clean mirror (rm jivo/ ecom/ under COMBINED)"
rm -rf "$COMBINED/jivo" "$COMBINED/ecom"

# ---- 2. lossless copy + byte-exact proof ------------------------------------
log "step 2: combined_migrate.py (lossless copy + sha256 proof)"
"$PY" "$GEN_DIR/combined_migrate.py" >>"$LOG" 2>&1 \
    || { alert "combined_migrate.py FAILED (lossless copy check)"; exit 3; }

# ---- 3. semantic link layer (cheap re-injection from cache) -----------------
# Run BEFORE the backbone so the backbone's manifest is computed over the FINAL
# on-disk state (honest zero-loss proof covering both appended link layers).
if [ "$RUN_SEMANTIC" = "yes" ] || \
   { [ "$RUN_SEMANTIC" = "auto" ] && ls "$COMBINED"/.links/domain-*.json >/dev/null 2>&1; }; then
    log "step 3: combined_inject_links.py (re-apply cached semantic links)"
    "$PY" "$GEN_DIR/combined_inject_links.py" >>"$LOG" 2>&1 \
        || { alert "combined_inject_links.py FAILED"; exit 4; }
else
    log "step 3: semantic links skipped (no .links cache or disabled)"
fi

# ---- 4. backbone: products/hubs/Home + deterministic links + manifest -------
log "step 4: combined_backbone.py (backbone + deterministic ## Related + manifest)"
"$PY" "$GEN_DIR/combined_backbone.py" >>"$LOG" 2>&1 \
    || { alert "combined_backbone.py FAILED"; exit 5; }

# ---- 5. VERIFY the freshly-built vault BEFORE touching the repo --------------
# Fail-closed: if zero-loss, structure, regression, or link integrity fails, we
# never sync the bad build into the repo and never commit.
log "step 5: verify_databank.py on the fresh build (gate before repo sync)"
"$PY" "$REPO/bin/verify_databank.py" --vault "$COMBINED" \
      --baseline "$REPO/bin/.baseline.json" >>"$LOG" 2>&1 \
    || { alert "verification FAILED on fresh build — NOT committing"; exit 6; }

# ---- 6. sync the verified build into the repo (protect repo-only files) ------
log "step 6: rsync verified build -> repo"
rsync -a --delete \
    --exclude '.git/' \
    --exclude '.gitignore' \
    --exclude 'README.md' \
    --exclude 'RUNBOOK.md' \
    --exclude 'ARCHITECTURE.md' \
    --exclude 'VAULT-GUIDE.md' \
    --exclude 'DATA-MODEL.md' \
    --exclude 'intelligence/' \
    --exclude 'bin/' \
    --exclude '.daily_rebuild.lock' \
    --exclude 'daily_rebuild.log' \
    "$COMBINED"/ "$REPO"/ >>"$LOG" 2>&1 \
    || { alert "rsync into repo FAILED"; exit 7; }

# ---- 7. re-verify the synced repo AND update the baseline --------------------
log "step 7: verify_databank.py on the synced repo (+ update baseline)"
"$PY" "$REPO/bin/verify_databank.py" --vault "$REPO" --update-baseline >>"$LOG" 2>&1 \
    || { alert "verification FAILED on synced repo — restoring last good commit";
         (cd "$REPO" && git reset --hard HEAD && git clean -fd) >>"$LOG" 2>&1 || true;
         exit 8; }

# ---- 8. commit only if something changed ------------------------------------
cd "$REPO"
git add -A
if git diff --cached --quiet; then
    log "step 8: no changes vs last commit — nothing to commit (clean exit)"
    log "=== daily_rebuild done (no-op) ==="
    exit 0
fi

PRODUCTS=$(ls "$REPO"/products/*.md 2>/dev/null | wc -l | tr -d ' ')
HUBS=$(ls "$REPO"/hubs/*.md 2>/dev/null | wc -l | tr -d ' ')
DAY=$(date -u +%Y-%m-%d)
git commit -q -m "data-bank refresh ${DAY} — ${PRODUCTS} products / ${HUBS} hubs (zero-loss verified)" \
    -m "Deterministic full REPLACE from current source vaults; verify_databank.py PASS (lossless + link integrity)." \
    >>"$LOG" 2>&1 \
    || { alert "git commit FAILED"; exit 9; }

log "step 8: committed refresh ${DAY} (${PRODUCTS} products / ${HUBS} hubs)"
log "=== daily_rebuild done (committed) ==="
# NOTE: this script NEVER pushes. The owner pushes (the classifier blocks Claude
# from pushing the proprietary dataset). See RUNBOOK.md.
exit 0
